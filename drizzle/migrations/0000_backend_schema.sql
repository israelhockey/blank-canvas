-- Saves a website form: matches or creates the customer by phone, logs the lead,
-- and for bookings creates a requested job on the calendar.
create or replace function public.submit_lead(p jsonb)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_type text := coalesce(p ->> 'type', 'contact');
  v_phone text := regexp_replace(coalesce(p ->> 'phone', ''), '\D', '', 'g');
  v_name text := left(coalesce(nullif(trim(p ->> 'name'), ''), nullif(trim(p ->> 'business'), ''), 'Website visitor'), 120);
  v_email text := nullif(left(trim(coalesce(p ->> 'email', '')), 200), '');
  v_customer uuid;
  v_lead uuid;
begin
  if v_type not in ('booking', 'walkthrough', 'quote', 'contact') then
    raise exception 'invalid lead type';
  end if;
  if length(v_phone) = 11 and left(v_phone, 1) = '1' then
    v_phone := substr(v_phone, 2);
  end if;
  if length(v_phone) <> 10 then
    raise exception 'invalid phone';
  end if;

  select id into v_customer from customers where phone_digits = v_phone;
  if v_customer is null then
    insert into customers (name, company, phone, phone_digits, email, source, stage)
    values (v_name, nullif(left(trim(coalesce(p ->> 'business', '')), 160), ''), left(p ->> 'phone', 40), v_phone,
            v_email, left(p ->> 'source', 300), 'new')
    returning id into v_customer;
  else
    update customers
      set email = coalesce(email, v_email),
          stage = case when stage in ('lost', 'paid', 'completed') then 'new' else stage end,
          updated_at = now()
      where id = v_customer;
  end if;

  insert into leads (type, customer_id, name, phone, email, zip, details, source, page, visitor_id)
  values (v_type, v_customer, v_name, left(p ->> 'phone', 40), v_email, left(p ->> 'zip', 10),
          coalesce(p -> 'details', '{}'::jsonb), left(p ->> 'source', 300), left(p ->> 'page', 300),
          left(p ->> 'visitor_id', 80))
  returning id into v_lead;

  if v_type = 'booking' and nullif(p ->> 'day_iso', '') is not null then
    insert into jobs (customer_id, lead_id, scheduled_date, arrival_window, status, items, subtotal, tax, total, zip, notes)
    values (v_customer, v_lead, (p ->> 'day_iso')::date, left(p ->> 'window', 40), 'requested',
            coalesce(p -> 'details' -> 'items', '[]'::jsonb),
            coalesce((p -> 'details' ->> 'subtotal')::numeric, 0),
            coalesce((p -> 'details' ->> 'tax')::numeric, 0),
            coalesce((p -> 'details' ->> 'total')::numeric, 0),
            left(p ->> 'zip', 10), left(p -> 'details' ->> 'notes', 2000));
  end if;

  insert into activities (customer_id, lead_id, kind, body)
  values (v_customer, v_lead, 'system', 'New ' || v_type || ' request from the website');

  return v_lead;
end $$;

-- Which arrival windows are taken (for the public booking form). Returns counts only, no customer data.
create or replace function public.booked_slots(p_from date, p_to date)
returns table (day date, arrival_window text, n bigint)
language sql stable security definer set search_path = public as $$
  select j.scheduled_date, j.arrival_window, count(*)
    from jobs j
   where j.scheduled_date between p_from and p_to and j.status <> 'canceled'
   group by 1, 2
  union all
  select b.day, coalesce(b.arrival_window, '*'), 999
    from blocked_slots b
   where b.day between p_from and p_to
$$;

-- Public quote page: returns a sent quote by its secret link and marks it viewed.
create or replace function public.get_quote(p_token text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare q quotes; c customers;
begin
  select * into q from quotes where token = p_token;
  if not found or q.status = 'draft' then return null; end if;
  if q.status = 'sent' then
    update quotes set status = 'viewed', viewed_at = now() where id = q.id;
    q.status := 'viewed';
  end if;
  select * into c from customers where id = q.customer_id;
  return jsonb_build_object(
    'number', q.number, 'title', q.title, 'status', q.status, 'items', q.items,
    'subtotal', q.subtotal, 'tax', q.tax, 'total', q.total, 'notes', q.notes,
    'expires_at', q.expires_at, 'created_at', q.created_at, 'accepted_at', q.accepted_at,
    'customer_name', c.name);
end $$;

-- Customer accepts a quote online: marks it accepted, books a requested job, updates the pipeline.
create or replace function public.accept_quote(p_token text, p_day date default null, p_window text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare q quotes; v_job uuid;
begin
  select * into q from quotes where token = p_token;
  if not found or q.status in ('draft', 'declined') then
    return jsonb_build_object('ok', false, 'error', 'not_available');
  end if;
  if q.expires_at is not null and q.expires_at < current_date then
    update quotes set status = 'expired' where id = q.id;
    return jsonb_build_object('ok', false, 'error', 'expired');
  end if;
  if q.status = 'accepted' then
    return jsonb_build_object('ok', true, 'already', true);
  end if;

  update quotes set status = 'accepted', accepted_at = now(), updated_at = now() where id = q.id;

  if q.job_id is null then
    insert into jobs (customer_id, scheduled_date, arrival_window, status, items, subtotal, tax, total, notes)
    values (q.customer_id, p_day, left(p_window, 40), 'requested', q.items, q.subtotal, q.tax, q.total,
            'Booked from quote #' || q.number)
    returning id into v_job;
    update quotes set job_id = v_job where id = q.id;
  else
    update jobs set scheduled_date = coalesce(p_day, scheduled_date),
                    arrival_window = coalesce(left(p_window, 40), arrival_window),
                    updated_at = now()
     where id = q.job_id;
  end if;

  update customers set stage = 'booked', updated_at = now() where id = q.customer_id;
  insert into activities (customer_id, job_id, kind, body)
  values (q.customer_id, coalesce(v_job, q.job_id), 'system', 'Customer accepted quote #' || q.number || ' online');
  return jsonb_build_object('ok', true);
end $$;

-- Team-only stats summary for the dashboard.
create or replace function public.site_stats(p_from timestamptz, p_to timestamptz)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare r jsonb;
begin
  if not public.is_team(auth.uid()) then return null; end if;
  with ev as (select * from site_events where created_at >= p_from and created_at < p_to)
  select jsonb_build_object(
    'visitors', (select count(distinct visitor_id) from ev),
    'pageviews', (select count(*) from ev where event = 'page_view'),
    'by_day', (select coalesce(jsonb_agg(x order by x.day), '[]'::jsonb) from (
        select (created_at at time zone 'America/Chicago')::date as day,
               count(distinct visitor_id) as visitors,
               count(*) filter (where event = 'page_view') as pageviews
          from ev group by 1) x),
    'events', (select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select event, coalesce(label, '') as label, count(*) as n
          from ev where event <> 'page_view' group by 1, 2 order by 3 desc limit 60) x),
    'pages', (select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select path, count(*) as n from ev where event = 'page_view' group by 1 order by 2 desc limit 25) x),
    'sources', (select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select coalesce(nullif(source, ''), 'direct') as source, count(distinct visitor_id) as visitors
          from ev group by 1 order by 2 desc limit 25) x),
    'funnel', jsonb_build_object(
        'visited', (select count(distinct visitor_id) from ev),
        'priced', (select count(distinct visitor_id) from ev where event in ('price_change', 'preset')),
        'started_booking', (select count(distinct visitor_id) from ev where event = 'booking_start'),
        'booked', (select count(distinct visitor_id) from ev where event = 'booking_submit')),
    'leads', (select count(*) from leads where created_at >= p_from and created_at < p_to)
  ) into r;
  return r;
end $$;

