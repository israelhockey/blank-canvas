-- ============ Team & access ============
create type public.app_role as enum ('owner', 'partner');

create table public.team_members (
  user_id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  display_name text,
  role public.app_role not null default 'owner',
  created_at timestamptz not null default now()
);

create table public.team_invites (
  email text primary key,
  role public.app_role not null default 'owner',
  display_name text,
  created_at timestamptz not null default now()
);

create or replace function public.is_team(_uid uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.team_members where user_id = _uid)
$$;

create or replace function public.handle_new_team_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.team_members (user_id, email, display_name, role)
  select new.id, new.email, i.display_name, i.role
  from public.team_invites i
  where lower(i.email) = lower(new.email)
  on conflict (user_id) do nothing;
  return new;
end $$;

create trigger on_auth_user_created_team
  after insert on auth.users
  for each row execute function public.handle_new_team_user();

-- Lets an invited user who signed up before the invite existed claim access.
create or replace function public.claim_team_access()
returns boolean language plpgsql security definer set search_path = public as $$
declare v_email text;
begin
  select email into v_email from auth.users where id = auth.uid();
  if v_email is null then return false; end if;
  insert into public.team_members (user_id, email, display_name, role)
  select auth.uid(), v_email, i.display_name, i.role
  from public.team_invites i where lower(i.email) = lower(v_email)
  on conflict (user_id) do nothing;
  return public.is_team(auth.uid());
end $$;

